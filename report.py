"""Static charts and a results table for the README.

Run after `python model.py`:  python report.py
Writes results/*.png and results/results.md.
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from backtest import backtest, equity_and_drawdown
from model import RESULTS_DIR, load

BLUE, ORANGE = "#2a78d6", "#eb6834"         # categorical slots 1 and 2
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"

plt.rcParams.update({
    "figure.dpi": 130, "font.size": 9, "axes.edgecolor": GRID, "axes.labelcolor": MUTED,
    "xtick.color": MUTED, "ytick.color": MUTED, "axes.grid": True, "grid.color": GRID,
    "grid.linewidth": 0.6, "axes.spines.top": False, "axes.spines.right": False,
    "axes.titlesize": 10, "axes.titleweight": "bold", "axes.titlecolor": INK,
    "legend.frameon": False, "lines.linewidth": 1.6,
})

NAMES = {"logreg": "Logistic regression", "lgbm": "LightGBM"}


def metrics_table(res: dict) -> pd.DataFrame:
    rows = []
    for variant, label in (("main", "Main"), ("strict_timing", "Strict timing")):
        exps = res["variants"][variant]["exps"]
        for (fam, fs), e in exps.items():
            t = e["test"]
            rows.append({"Timing": label, "Model": NAMES[fam],
                         "Features": "base + FOMC" if fs == "fomc" else "base",
                         "CV AUC (train)": e["cv_auc"], "Test AUC": t["auc"],
                         "Precision": t["precision"], "Recall": t["recall"],
                         "Flagged": t["flag_rate"]})
    g = res["gvz_only"]
    rows.append({"Timing": "Main", "Model": "GVZ level only", "Features": "gvz",
                 "CV AUC (train)": g["cv_auc"], "Test AUC": g["test"]["auc"],
                 "Precision": g["test"]["precision"], "Recall": g["test"]["recall"],
                 "Flagged": g["test"]["flag_rate"]})
    return pd.DataFrame(rows)


def fmt(df: pd.DataFrame, pct_cols=(), dec_cols=()) -> str:
    df = df.copy()
    for c in pct_cols:
        df[c] = df[c].map(lambda v: f"{v:.1%}")
    for c in dec_cols:
        df[c] = df[c].map(lambda v: f"{v:.3f}")
    return df.to_markdown(index=False)


def main() -> None:
    res = load()
    d = res["variants"]["main"]["data"]
    fam, fs = res["strategy_model"]
    exp = res["variants"]["main"]["exps"][(fam, fs)]
    bt = backtest(res)
    out = RESULTS_DIR
    lines = [f"# Results (generated by report.py)\n",
             f"Label threshold: |next-day log return| > {d['threshold']:.3%} "
             f"(80th pct of 2010-2020). Test base rate: {d['test']['y'].mean():.1%}.\n"]

    mt = metrics_table(res)
    lines += ["## Classification (test = 2021 onward)\n",
              fmt(mt, pct_cols=["Precision", "Recall", "Flagged"],
                  dec_cols=["CV AUC (train)", "Test AUC"]), ""]

    lines += ["## FOMC flag: test AUC with minus without (95% block-bootstrap CI)\n"]
    for f, v in res["fomc_test"].items():
        lines.append(f"- {NAMES[f]}: {v['diff']:+.4f} [{v['lo']:+.4f}, {v['hi']:+.4f}]")
    for k, v in res["fomc_rates"].items():
        lines.append(f"- {k}: P(high-vol | day after FOMC) = {v['p_high_after_fomc']:.1%} "
                     f"over {v['n_events']} events vs {v['p_high_other']:.1%} otherwise")
    lines.append("")

    lines += ["## Confusion matrices (test)\n"]
    for (f, s), e in res["variants"]["main"]["exps"].items():
        if s == res["chosen"][f]:
            c = e["test"]["confusion"]
            lines.append(f"- {NAMES[f]} ({s}): TN {c['tn']}, FP {c['fp']}, FN {c['fn']}, TP {c['tp']}")
    lines.append("")

    lines += ["## Strategy (test period)\n"]
    srows = []
    for variant, vlabel in (("main", "Main"), ("strict_timing", "Strict timing")):
        for f in ("logreg", "lgbm"):
            b = backtest(res, family=f, variant=variant)
            s = b["stats"]["Halve on predicted high-vol"]
            srows.append({"Timing": vlabel, "Strategy": f"Halve ({NAMES[f]})",
                          "Ann. return": s.ann_return, "Ann. vol": s.ann_vol,
                          "Sharpe": s.sharpe, "Max DD": s.max_dd,
                          "Avg exposure": s.avg_exposure, "Position changes": int(s.n_changes),
                          "Gross Sharpe > random": b["random"]["pct_beaten"]})
    s = bt["stats"]["Buy & hold"]
    srows.append({"Timing": "-", "Strategy": "Buy & hold", "Ann. return": s.ann_return,
                  "Ann. vol": s.ann_vol, "Sharpe": s.sharpe, "Max DD": s.max_dd,
                  "Avg exposure": 1.0, "Position changes": 0, "Gross Sharpe > random": float("nan")})
    st = pd.DataFrame(srows)
    st["Gross Sharpe > random"] = st["Gross Sharpe > random"].map(
        lambda v: "-" if pd.isna(v) else f"{v:.1%}")
    lines += [fmt(st, pct_cols=["Ann. return", "Ann. vol", "Max DD"],
                  dec_cols=["Sharpe", "Avg exposure"]), ""]
    r = bt["random"]
    lines.append(f"Random-halving control ({NAMES[fam]}, gross of costs): median Sharpe "
                 f"{r['sharpe_median']:.2f} (5-95%: {r['sharpe_p5']:.2f}-{r['sharpe_p95']:.2f}) "
                 f"vs strategy gross {r['strategy_gross_sharpe']:.2f}.")
    (out / "results.md").write_text("\n".join(lines) + "\n")

    # --- charts --------------------------------------------------------------
    flags = exp["p_test"] >= exp["cutoff"]
    close = d["test"]["close"]
    fig, ax = plt.subplots(figsize=(9, 3.4))
    ax.plot(close.index, close, color=MUTED, lw=1.2, label="GC=F close")
    ax.scatter(close.index[flags], close[flags], s=9, color=ORANGE, zorder=3,
               label="Predicted high-vol next day", linewidths=0)
    ax.set_title(f"Gold futures with predicted high-vol days ({NAMES[fam]}, test period)")
    ax.set_ylabel("USD / oz"); ax.legend(loc="upper left")
    fig.tight_layout(); fig.savefig(out / "price_signals.png"); plt.close(fig)

    eq, dd = equity_and_drawdown(bt["returns"])
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(9, 5), sharex=True,
                                 gridspec_kw={"height_ratios": [2, 1]})
    a1.plot(eq.index, eq.strategy, color=BLUE, label="Halve on predicted high-vol")
    a1.plot(eq.index, eq.buy_hold, color=ORANGE, label="Buy & hold")
    a1.set_title("Equity curve (growth of 1, after costs)"); a1.legend(loc="upper left")
    a2.plot(dd.index, dd.strategy * 100, color=BLUE)
    a2.plot(dd.index, dd.buy_hold * 100, color=ORANGE)
    a2.set_title("Drawdown"); a2.set_ylabel("%")
    fig.tight_layout(); fig.savefig(out / "equity_drawdown.png"); plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
    for ax, f, title in zip(axes, ("lgbm", "logreg"),
                            ("LightGBM: mean |SHAP| (test)", "Logistic: |std. coefficient|")):
        imp = res["importance"][f]["importance"].iloc[::-1]
        ax.barh(imp.index, imp.values, color=BLUE, height=0.6)
        ax.set_title(title); ax.grid(axis="y", visible=False)
    fig.tight_layout(); fig.savefig(out / "feature_importance.png"); plt.close(fig)
    print((out / "results.md").read_text())


if __name__ == "__main__":
    main()
